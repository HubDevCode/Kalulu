// providerIcon picks the sidebar icon of a provider key.
func providerIcon(key string) fyne.Resource {
	switch key {
	case "local":
		return iconLibrary
	case "radio", "cliamp":
		return iconRadio
	case "podcast", "podcasts", "audiobookshelf":
		return iconPodcast
	case "history":
		return theme.HistoryIcon()
	case "favorites":
		return iconHeart
	}
	return iconCloud
}
